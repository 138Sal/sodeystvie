/**
 * Сборка адаптивных изображений из assets-src/images.
 *
 * Для каждого исходника создаются AVIF/WebP шириной 480/960/… и манифест
 * src/data/images.generated.ts, который использует компонент <Picture>.
 * Страница image-credits.html получает маленькие превью вместо полноразмерных JPG.
 *
 * Запуск: npm run images
 */

import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';

const SRC = 'assets-src/images';
const OUT = 'public/images';
const CREDITS = path.join(OUT, 'credits');
const MANIFEST = 'src/data/images.generated.ts';

const CREDIT_IMAGES = [
  'alley-fog',
  'cemetery-alley',
  'chelyabinsk',
  'crosses-cluster',
  'fence-granite',
  'flowers',
  'candles',
  'monument-cross',
  'monument-family',
  'monument-premium',
  'orthodox-graves',
];

const isSource = (file) => /\.(jpe?g|png)$/i.test(file);
const nameOf = (file) => path.parse(file).name;

await fs.rm(OUT, { recursive: true, force: true });
await fs.mkdir(CREDITS, { recursive: true });

const files = (await fs.readdir(SRC)).filter(isSource).sort();
const manifest = {};

for (const file of files) {
  const name = nameOf(file);
  const sourcePath = path.join(SRC, file);
  const meta = await sharp(sourcePath).metadata();
  const sourceWidth = meta.width ?? 0;
  const sourceHeight = meta.height ?? 0;

  const rawWidths = [480, 960, 1600, sourceWidth <= 1600 ? sourceWidth : 0].filter(
    (width) => width > 0 && width <= sourceWidth,
  );
  const widths = [...new Set(rawWidths)].sort((a, b) => a - b);

  const sources = [];
  for (const width of widths) {
    const height = Math.round((sourceHeight / sourceWidth) * width);
    const avifName = `${name}-${width}.avif`;
    const webpName = `${name}-${width}.webp`;

    await sharp(sourcePath)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .avif({ quality: 45, effort: 5 })
      .toFile(path.join(OUT, avifName));

    await sharp(sourcePath)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 70, effort: 5 })
      .toFile(path.join(OUT, webpName));

    sources.push({ width, height, avif: `images/${avifName}`, webp: `images/${webpName}` });
  }

  const fallback = sources.find((source) => source.width >= 960) ?? sources[sources.length - 1];

  manifest[name] = {
    width: sourceWidth,
    height: sourceHeight,
    src: fallback.webp,
    sources,
  };
}

for (const name of CREDIT_IMAGES) {
  const source = path.join(SRC, `${name}.jpg`);
  try {
    await fs.access(source);
  } catch {
    continue;
  }
  await sharp(source)
    .rotate()
    .resize(200, 140, { fit: 'cover', position: 'centre' })
    .jpeg({ quality: 78 })
    .toFile(path.join(CREDITS, `${name}.jpg`));
}

await sharp(path.join(SRC, 'team-1.jpg'))
  .rotate()
  .resize(1200, 630, { fit: 'cover', position: 'centre' })
  .jpeg({ quality: 84 })
  .toFile('public/og-image.jpg');

await sharp('public/favicon.svg').resize(180, 180).png().toFile('public/apple-touch-icon.png');

const typeFile = `// AUTO-GENERATED by scripts/images.mjs. Do not edit by hand.
export interface ImageSource {
  readonly width: number;
  readonly height: number;
  readonly avif: string;
  readonly webp: string;
}

export interface GeneratedImage {
  readonly width: number;
  readonly height: number;
  readonly src: string;
  readonly sources: readonly ImageSource[];
}

export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;

await fs.writeFile(MANIFEST, typeFile, 'utf8');

const total = (await fs.readdir(OUT)).length;
console.log(`images: ${files.length} sources -> ${total} files, manifest ${MANIFEST}`);
